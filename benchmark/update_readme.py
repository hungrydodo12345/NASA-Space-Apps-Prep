"""Write the benchmark results into README.md between the BENCHMARK markers.

Source: benchmark/results/benchmark_results.json when the full run has finished; otherwise the per-scene lines of a
running benchmark's log (pass --log), clearly marked as partial.
Usage: python benchmark/update_readme.py [--log path/to/bench.log]
"""
import os, re, sys, json, argparse, numpy as np
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
ap = argparse.ArgumentParser(); ap.add_argument("--log"); a = ap.parse_args()
RES = os.path.join(ROOT, "benchmark", "results", "benchmark_results.json"); README = os.path.join(ROOT, "README.md")
NAMES = {"raw": "Raw HiRISE, one pass (bicubic)", "current": "Our previous pipeline (ECC + CG Tikhonov)",
         "gpt": "**UCL pipeline** (our re-implementation of Tao & Muller 2016: Gotcha + PDE-TV, assumed blur)",
         "gpt+weights": "UCL + our weighting only", "gpt+blur": "UCL + our measured per-pass blur only",
         "full": "**This work** (Gotcha + weighted, change-masked PDE-TV + measured per-pass blur)", "oracle": "This work with exact motion (upper bound)"}
ORDER = ["raw", "current", "gpt", "gpt+weights", "gpt+blur", "full", "oracle"]

if os.path.exists(RES) and not a.log:
    R = json.load(open(RES)); A = R["A_simulation"]; partial = False
    sim = {m: {k: A[m][k]["values"] for k in ("err_6cm", "err_25cm", "artefact")} for m in ORDER if m in A}
    paired = A.get("paired_vs_gpt", {}); B = R.get("B_split_half_real"); C = R.get("C_rover_edge_real")
else:
    sim = {}
    for line in open(a.log):
        m = re.match(r"scene (\d+) (\S+)\s+err6\s+([\d.]+)% err25\s+([\d.]+)% artefact ([\d.]+)", line)
        if m:
            d = sim.setdefault(m.group(2), dict(err_6cm=[], err_25cm=[], artefact=[]))
            d["err_6cm"].append(float(m.group(3))); d["err_25cm"].append(float(m.group(4))); d["artefact"].append(float(m.group(5)))
    n = min(len(v["err_25cm"]) for v in sim.values()); sim = {k: {kk: vv[:n] for kk, vv in v.items()} for k, v in sim.items()}
    partial = True; paired = {}; B = C = None
    for m in sim:
        if m == "gpt": continue
        for k in ("err_6cm", "err_25cm", "artefact"):
            dl = np.array(sim[m][k]) - np.array(sim["gpt"][k]); paired[f"{m} - gpt, {k}"] = dict(mean=float(dl.mean()), scenes_better=int((dl < 0).sum()), scenes=len(dl))

n = len(sim["gpt"]["err_25cm"]); L = []
L.append("## Paper benchmark: this work vs the UCL pipeline (all on CPU)\n")
if partial: L.append(f"> **Partial results: {n} of 5 simulated scenes finished; real-HiRISE tests still running.** This table is regenerated by `benchmark/update_readme.py` when the run completes.\n")
L.append("Method details: [`docs/METHODS.md`](docs/METHODS.md). Code: [`benchmark/run_benchmark.py`](benchmark/run_benchmark.py). Data: [`benchmark/data_manifest.json`](benchmark/data_manifest.json).\n")
L.append("UCL did not release code or products. \"UCL pipeline\" is our re-implementation from the paper's equations, run on the same data and CPU.\n")
L.append(f"**A. Simulation with exact truth** ({n} scenes). Setup: fractal ground, 8 passes with the measured per-pass blur, non-rigid jitter, 3% noise, and one pass with a planted change. Every method estimates its own motion. The error columns are RMS error as % of the true scene contrast; lower is better.\n")
L.append("| Method | Error at native 25 cm | Error at 6.25 cm output pixel | Artefact at the planted change (× scene std) |")
L.append("|---|---|---|---|")
for m in ORDER:
    if m in sim:
        v = sim[m]; L.append(f"| {NAMES[m]} | {np.mean(v['err_25cm']):.1f}% | {np.mean(v['err_6cm']):.1f}% | {np.mean(v['artefact']):.2f} |")
L.append("")
g = lambda k: paired.get(f"full - gpt, {k}")
if g("err_25cm"):
    e25, e6, ar = g("err_25cm"), g("err_6cm"), g("artefact")
    rel = 100 * e25["mean"] / np.mean(sim["gpt"]["err_25cm"])
    ci = lambda d: f" (95% CI {d['ci95'][0]:+.2f} to {d['ci95'][1]:+.2f})" if "ci95" in d else ""
    L.append(f"**This work vs UCL, paired by scene:**\n")
    L.append(f"- **25 cm:** {e25['mean']:+.2f} points{ci(e25)}, a {abs(rel):.0f}% relative reduction. Better in {e25['scenes_better']}/{e25['scenes']} scenes.")
    L.append(f"- **Artefact at the planted change:** {ar['mean']:+.2f}{ci(ar)}. Better in {ar['scenes_better']}/{ar['scenes']} scenes.")
    L.append(f"- **6.25 cm:** {e6['mean']:+.2f} points{ci(e6)}. Better in {e6['scenes_better']}/{e6['scenes']} scenes.")
    L.append("")
    b6 = paired.get("gpt+blur - gpt, err_6cm")
    if b6 and b6["mean"] < e6["mean"]:
        L.append("- **Ablation:** at the 6.25 cm output pixel, adding only our measured blur to UCL does best. The weighting trades a little fine-pixel error for robustness to changes between passes.")
    w25 = paired.get("gpt+weights - gpt, err_25cm")
    if w25 and w25["mean"] > 0:
        L.append("- **Ablation:** weighting without the measured blur makes UCL worse. Its residual-based pass weights are misled by the wrong blur model, so the two changes must go together.")
    L.append("")
if B and "full" in B:
    L.append("**B. Real HiRISE, split-half consistency.** On a 32 m tile at 18.4472 N, 77.4127 E, 8 passes from 2007–2022 are split into two disjoint halves, each restored independently. The table gives the finest scale at which the two halves agree (coherence ≥ 0.5); smaller means more detail that is genuinely in the data.\n")
    L.append("| Method | Halves agree down to |"); L.append("|---|---|")
    for m in ORDER:
        if m in B and isinstance(B[m], dict): L.append(f"| {NAMES[m]} | {B[m]['consistent_down_to_cm']:.1f} cm |" if B[m]["consistent_down_to_cm"] else f"| {NAMES[m]} | n/a |")
    L.append("")
if C and "full" in C:
    L.append("**C. Real HiRISE, the parked rover's edge.** At the landing site, in 3 passes from sols 1–11, the table gives the width of Perseverance's edge in each restoration, together with the ringing that sharpening costs. Both ringing columns are a share of the rover's brightness step.\n")
    L.append("| Method | Edge width σ | Ringing (RMS) | Largest undershoot |"); L.append("|---|---|---|---|")
    for m in ORDER:
        if m in C and isinstance(C[m], dict) and C[m].get("edge_sigma_cm"):
            L.append(f"| {NAMES[m]} | {C[m]['edge_sigma_cm']:.1f} cm | {100 * C[m]['ringing_rms_of_amplitude']:.1f}% | {100 * C[m]['max_undershoot_of_amplitude']:.1f}% |")
    L.append("")
L.append("**What this does and does not show.**\n")
L.append("- **Gain at 25 cm.** It comes from two measured inputs, per-pass blur calibrated on the parked rover and per-pass/per-pixel weighting, added to UCL's method.")
L.append("- **No 5 cm claim.** Detail that repeats between independent sets of passes stops at roughly 30–40 cm. We do not claim the 5 cm resolution reported by UCL.")
L.append("- **Unverified confidences.** The confidence-scored fill is calibrated in simulation. The rover answer key is misregistered by metres at most stops, so it cannot verify sub-metre confidences; see METHODS Section 7.\n")
block = "<!-- BENCHMARK:START -->\n" + "\n".join(L) + "\n<!-- BENCHMARK:END -->"
s = open(README).read()
if "<!-- BENCHMARK:START -->" in s: s = re.sub(r"<!-- BENCHMARK:START -->.*?<!-- BENCHMARK:END -->", lambda _: block, s, flags=re.S)
else: s = s.replace("## How it works", block + "\n\n## How it works", 1)
open(README, "w").write(s); print(block)
