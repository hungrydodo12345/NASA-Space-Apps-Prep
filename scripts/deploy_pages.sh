#!/bin/sh
# Publish the playable game to the gh-pages branch (a separate, history-free branch: page + script + world tiles).
# Usage: sh scripts/deploy_pages.sh <world_dir> [work_dir]
# Then, once: GitHub -> repository Settings -> Pages -> "Deploy from a branch" -> gh-pages, folder / (root).
set -e
R=$(cd "$(dirname "$0")/.." && pwd); WORLD=$1; W=${2:-$(mktemp -d)}
rm -rf "$W"; mkdir -p "$W"; cd "$W"; git init -q; git checkout -q -b gh-pages
cp "$R/web/game/index.html" "$R/web/game/game.js" .; cp -r "$R/web/game/assets" .; mkdir data; cp -r "$WORLD"/tiles "$WORLD"/*.json "$WORLD"/overview.jpg data/
touch .nojekyll
cat > README.md <<'EOR'
# Jezero Explorer (GitHub Pages build)
Playable build of the game in `web/game/` of the main branches, with the world tiles in `data/`. Generated by `scripts/deploy_pages.sh`; do not edit by hand.
EOR
git remote add origin "$(git -C "$R" remote get-url origin)"
# build on top of the published branch if it exists, so a push only uploads what changed
if git fetch -q --depth 1 origin gh-pages 2>/dev/null; then git reset -q --soft FETCH_HEAD; fi
git add -A; git -c user.name="$(git -C "$R" config user.name || echo deploy)" -c user.email="$(git -C "$R" config user.email || echo deploy@localhost)" commit -q -m "Jezero Explorer: playable build (web/game + world tiles)

Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>
Claude-Session: https://claude.ai/code/session_01TwCFzmgE88qfQ6JD2uPsHE"
echo "built gh-pages in $W: $(du -sh . | cut -f1), $(git ls-files | wc -l) files"
